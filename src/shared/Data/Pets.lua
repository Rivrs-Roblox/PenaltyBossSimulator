for name, info in pairs(Pets) do
	if not string.find(name, "Gold ") and not string.find(name, "Rainbow ") then
		basePets[name] = info
	end
end

for _, Info in pairs(basePets) do
	if not string.find(Info.Name, "Gold ") and not string.find(Info.Name, "Rainbow ") then
		local GoldName = `Gold {Info.Name}`
		local RainbowName = `Rainbow {Info.Name}`

		if Info.Type == "Scaling" then
			if Info.Movement == "Fly" then
				Pets[GoldName] = {
					["Name"] = GoldName,
					["Type"] = "Scaling",
					["Multiplier"] = Info.Multiplier + 0.5,
					["Rarity"] = Info.Rarity,
					["Speed"] = Info.Speed * 1.5,
					["Movement"] = Info.Movement,
					["Higher"] = false,
				}

				Pets[RainbowName] = {
					["Name"] = RainbowName,
					["Type"] = "Scaling",
					["Multiplier"] = Info.Multiplier + 1,
					["Rarity"] = Info.Rarity,
					["Speed"] = Info.Speed * 1.5,
					["Movement"] = Info.Movement,
					["Higher"] = false,
				}
			else
				Pets[GoldName] = {
					["Name"] = GoldName,
					["Type"] = "Scaling",
					["Multiplier"] = Info.Multiplier + 0.5,
					["Rarity"] = Info.Rarity,
					["Speed"] = Info.Speed * 1.5,
					["Movement"] = Info.Movement,
				}

				Pets[RainbowName] = {
					["Name"] = RainbowName,
					["Type"] = "Scaling",
					["Multiplier"] = Info.Multiplier + 1,
					["Rarity"] = Info.Rarity,
					["Speed"] = Info.Speed * 1.5,
					["Movement"] = Info.Movement,
				}
			end
		else
			if Info.Movement == "Fly" then
				Pets[GoldName] = {
					["Name"] = GoldName,
					["Power"] = Info.Power * 2,
					["Rarity"] = Info.Rarity,
					["Speed"] = Info.Speed * 1.5,
					["Movement"] = Info.Movement,
					["Higher"] = false,
				}

				Pets[RainbowName] = {
					["Name"] = RainbowName,
					["Power"] = Info.Power * 3,
					["Rarity"] = Info.Rarity,
					["Speed"] = Info.Speed * 1.5,
					["Movement"] = Info.Movement,
					["Higher"] = false,
				}
			else
				Pets[GoldName] = {
					["Name"] = GoldName,
					["Power"] = Info.Power * 2,
					["Rarity"] = Info.Rarity,
					["Speed"] = Info.Speed * 1.5,
					["Movement"] = Info.Movement,
				}

				Pets[RainbowName] = {
					["Name"] = RainbowName,
					["Power"] = Info.Power * 3,
					["Rarity"] = Info.Rarity,
					["Speed"] = Info.Speed * 1.5,
					["Movement"] = Info.Movement,
				}
